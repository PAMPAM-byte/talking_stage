import { test, expect } from '@playwright/test';

for(const width of [390,1440])test(`expressions send and render at ${width}px`,async({page})=>{
  await page.setViewportSize({width,height:900});
  await page.goto('/dev/chat-delivery?scenario=disabled');
  const input=page.getByRole('textbox',{name:'Message Amara'});
  await input.fill('Hey you');
  await input.evaluate((element:HTMLTextAreaElement)=>element.setSelectionRange(3,3));
  const trigger=page.getByRole('button',{name:'Emoji, stickers and GIFs',exact:true});
  await trigger.click();
  await page.getByRole('button',{name:'😊 smile happy',exact:true}).click();
  await expect(input).toHaveValue('Hey😊 you');
  await trigger.click();
  await page.getByRole('button',{name:'Send message',exact:true}).click();
  await expect(page.getByRole('log').getByText('Hey😊 you',{exact:true})).toBeVisible();
  await expect(page.getByLabel('Saved',{exact:true})).toBeVisible();
  await trigger.click();
  await page.getByRole('button',{name:'Stickers',exact:true}).click();
  await page.getByLabel('Search expressions').fill('hug');
  await page.getByLabel('Search expressions').press('Enter');
  await expect(page.getByRole('log').locator('.message-turn')).toHaveCount(1);
  await page.getByRole('button',{name:'Sticker: Come here',exact:true}).click();
  await expect(page.getByLabel('Selected reaction')).toBeVisible();
  await input.fill('You deserve this');
  await page.getByRole('button',{name:'Send message',exact:true}).click();
  await expect(page.getByRole('log').getByRole('img',{name:'Sticker: Come here',exact:true})).toBeVisible();
  await expect(page.getByRole('log').getByText('You deserve this',{exact:true})).toBeVisible();
  await expect(page.getByLabel('Saved',{exact:true})).toHaveCount(2);
  await trigger.click();
  await page.getByRole('button',{name:'GIFs',exact:true}).click();
  await expect(page.getByRole('button',{name:/^GIF: /})).toHaveCount(20);
  await page.getByRole('button',{name:'GIF: You have finished me',exact:true}).click();
  await page.getByRole('button',{name:'Send message',exact:true}).click();
  const gif=page.getByRole('log').getByRole('img',{name:'GIF: You have finished me',exact:true});
  await expect(gif).toBeVisible();
  await expect(gif).toHaveAttribute('src','/chat-reactions/laugh.gif');
  await expect(page.getByLabel('Saved',{exact:true})).toHaveCount(3);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.screenshot({path:`.local-services/chat-expressions-${width}.png`});
});

test('new Naija GIFs send and character media replies render with captions',async({page})=>{
  await page.setViewportSize({width:390,height:844});
  await page.goto('/dev/chat-delivery?scenario=disabled');
  await page.getByRole('button',{name:'Emoji, stickers and GIFs',exact:true}).click();
  await page.getByRole('button',{name:'GIFs',exact:true}).click();
  await page.getByLabel('Search expressions').fill('love');
  await page.getByRole('button',{name:'GIF: My person',exact:true}).click();
  await page.getByRole('textbox',{name:'Message Amara'}).fill('This is you');
  await page.getByRole('button',{name:'Send message',exact:true}).click();
  const sent=page.getByRole('log').getByRole('img',{name:'GIF: My person',exact:true});
  await expect(sent).toHaveAttribute('src','/chat-reactions/my-person.gif');
  await expect(page.getByLabel('Saved',{exact:true})).toBeVisible();
  await expect.poll(()=>sent.evaluate((image:HTMLImageElement)=>image.naturalWidth)).toBe(192);
  await page.goto('/dev/chat-delivery?scenario=expressions');
  await expect(page.getByTestId('character-gif').getByRole('img',{name:'GIF: Omo, I don laugh'})).toBeVisible();
  await expect(page.getByTestId('character-gif').getByText('You got me too 😂',{exact:true})).toBeVisible();
  await expect(page.getByTestId('character-sticker').getByRole('img',{name:'Sticker: My person'})).toBeVisible();
  await expect(page.getByRole('log')).not.toContainText('[[ts:');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.screenshot({path:'.local-services/chat-character-reactions.png'});
  await page.emulateMedia({reducedMotion:'reduce'});
  const received=page.getByTestId('character-gif').getByRole('img');
  await expect.poll(()=>received.evaluate((image:HTMLImageElement)=>image.currentSrc)).toContain('/chat-reactions/omo-laugh.svg');
});

test('picker dismissal, draft retention, failed-media retry and reduced motion',async({page})=>{
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.goto('/dev/chat-delivery?scenario=disabled');
  const trigger=page.getByRole('button',{name:'Emoji, stickers and GIFs',exact:true});
  await trigger.click();
  await page.getByLabel('Search expressions').fill('nothing-matches');
  await expect(page.getByText('No reactions found. Try “love” or “laugh”.')).toBeVisible();
  await page.getByLabel('Search expressions').press('Escape');
  await expect(trigger).toBeFocused();
  await trigger.click();
  await page.getByRole('button',{name:'GIFs',exact:true}).click();
  await page.getByRole('button',{name:'GIF: Heart eyes',exact:true}).click();
  await page.getByLabel('Remove reaction').click();
  await expect(page.getByRole('button',{name:'Send message',exact:true})).toBeDisabled();
  await trigger.click();
  await page.getByRole('button',{name:'GIF: Heart eyes',exact:true}).click();
  await page.getByRole('button',{name:'Fail next save',exact:true}).click();
  await page.getByRole('button',{name:'Send message',exact:true}).click();
  await expect(page.getByRole('button',{name:'Retry sending',exact:true})).toBeVisible();
  const client=await page.locator('.message-turn--outgoing').getAttribute('data-client-id');
  await page.getByRole('button',{name:'Retry sending',exact:true}).click();
  await expect(page.getByLabel('Saved',{exact:true})).toBeVisible();
  await expect(page.locator(`[data-client-id="${client}"]`)).toHaveCount(1);
  const image=page.getByRole('log').getByRole('img',{name:'GIF: Heart eyes',exact:true});
  await expect(image).toBeVisible();
  await expect.poll(()=>image.evaluate((element:HTMLImageElement)=>element.currentSrc)).toContain('/chat-reactions/love.svg');
});
