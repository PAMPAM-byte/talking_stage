import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
const db = new PGlite();
const admin = '00000000-0000-4000-8000-000000000001';
const user = '00000000-0000-4000-8000-000000000002';
const incomplete = '00000000-0000-4000-8000-000000000003';
try {
  await db.exec(`create role anon; create role authenticated; create schema auth;
    create table auth.users(id uuid primary key, raw_user_meta_data jsonb not null default '{}');
    create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
    grant usage on schema auth,public to authenticated,anon; grant execute on function auth.uid() to authenticated,anon;`);
  for (const migration of ['202610080001_foundation.sql','202610080002_cast_drafts.sql']) await db.exec(await readFile(`supabase/migrations/${migration}`, 'utf8'));
  await db.exec(`insert into auth.users values('${admin}','{"adult_declaration":"18-plus-v1"}'),('${user}','{"adult_declaration":"18-plus-v1","role":"admin"}'),('${incomplete}','{}');
    update public.profiles set display_name='Test',genders=array['woman'],ai_consent_at=now(),onboarding_complete=true where id in ('${admin}','${user}');
    insert into private.user_roles(user_id,role) values('${admin}','admin'),('${incomplete}','admin');`);
  const actor = async (id, role = 'authenticated') => db.exec(`reset role; set role ${role}; select set_config('request.jwt.claim.sub','${id}',false);`);
  const profile = { name: 'Draft adult', age: 25, gender: 'woman', fictionalLocation: 'Lagos', occupation: 'Designer', bio: 'A fictional adult.', conversationClue: 'Tell me about your favourite music.', interests: ['Music'], personalityTags: ['Warm'] };
  const save = (id = null, version = 0, p = profile, direction = 'PRIVATE TEST DIRECTION') => db.query('select public.admin_save_cast($1,$2,$3,$4) as id', [id, version, JSON.stringify(p), direction]);
  await actor(user); await assert.rejects(save(), /forbidden/); await assert.rejects(db.query('select public.admin_list_cast()'), /forbidden/);
  await actor(incomplete); await assert.rejects(save(), /forbidden/);
  await actor('', 'anon'); await assert.rejects(save(), /permission denied/);
  await actor(admin);
  await assert.rejects(save(null, 0, { ...profile, age: 17 }), /invalid_cast/);
  await assert.rejects(save(null, 0, { ...profile, role: 'admin' }), /invalid_cast/);
  const id = (await save()).rows[0].id;
  const list = () => db.query('select public.admin_list_cast() as drafts');
  assert.equal((await list()).rows[0].drafts[0].instructionVersion, 1);
  await save(id, 1, { ...profile, name: 'Edited draft' });
  assert.equal((await list()).rows[0].drafts[0].instructionVersion, 1);
  await assert.rejects(save(id, 1), /conflict/);
  await save(id, 2, { ...profile, name: 'Revised draft' }, 'REVISED PRIVATE DIRECTION');
  assert.equal((await list()).rows[0].drafts[0].instructionVersion, 2);
  await db.exec('reset role');
  await db.query(`update public.characters set status='published',name='Published snapshot' where id=$1`, [id]);
  await actor(admin); await save(id, 3);
  await actor(user);
  assert.equal((await db.query('select name from public.characters')).rows[0].name, 'Published snapshot', 'draft edits preserve published copy');
  await assert.rejects(db.query('select * from private.cast_drafts'), /permission denied/);
  await assert.rejects(db.query(`update public.characters set name='Forged'`), /permission denied/);
  await assert.rejects(db.query('select public.admin_deactivate_cast($1,4)', [id]), /forbidden/);
  await actor(admin); await db.query('select public.admin_deactivate_cast($1,4)', [id]);
  await actor(user); assert.equal((await db.query('select * from public.characters')).rows.length, 0, 'deactivation removes customer access');
  await db.exec('reset role');
  assert.equal(Number((await db.query('select count(*) as n from private.admin_audit')).rows[0].n), 5);
  await db.exec(`delete from private.request_limits where user_id='${admin}' and action='cast'`);
  await actor(admin);
  for (let count = 0; count < 30; count++) await save();
  await assert.rejects(save(), /rate_limited/);
  await db.exec('reset role');
  assert.equal(Number((await db.query(`select attempts from private.request_limits where user_id='${admin}' and action='cast'`)).rows[0].attempts), 30);
  console.log('Cast database checks passed: roles/adult access, validation, versions, private direction, unchanged published snapshot, deactivation, audit and mutation limits.');
} finally { await db.close(); }
